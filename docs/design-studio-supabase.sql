-- AIAS Memphis Design Studio community backend
-- Run this in a chapter-owned Supabase project. It is intentionally rerunnable.
-- IMPORTANT: use only the browser-safe publishable key in the website config.
-- Never place a secret/service_role key in this repository.

create extension if not exists pgcrypto;

create table if not exists public.community_settings (
  id boolean primary key default true check (id = true),
  mode text not null default 'auto' check (mode in ('auto','moderated'))
);
insert into public.community_settings (id, mode)
values (true, 'auto')
on conflict (id) do nothing;

create table if not exists public.community_designs (
  id uuid primary key default gen_random_uuid(),
  owner_id uuid not null,
  title text not null check (char_length(title) between 1 and 80),
  designer text not null check (char_length(designer) between 1 and 80),
  caption text not null default '' check (char_length(caption) <= 280),
  design_code text not null check (
    char_length(design_code) between 8 and 24000
    and design_code ~ '^[A-Za-z0-9_-]+$'
  ),
  status text not null default 'published' check (status in ('pending','published','hidden')),
  featured boolean not null default false,
  parent_id uuid references public.community_designs(id) on delete set null,
  root_id uuid references public.community_designs(id) on delete set null,
  remix_depth smallint not null default 0 check (remix_depth between 0 and 20),
  remix_note text not null default '' check (char_length(remix_note) <= 180),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

