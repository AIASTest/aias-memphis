-- Prevent one anonymous browser identity from flooding the live wall.
create or replace function public.enforce_community_design_post_limit()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if (
    select count(*)
    from public.community_designs
    where owner_id = new.owner_id
      and created_at > now() - interval '1 hour'
  ) >= 5 then
    raise exception 'Community post limit reached: maximum 5 designs per hour';
  end if;

  if (
    select count(*)
    from public.community_designs
    where owner_id = new.owner_id
      and created_at > now() - interval '24 hours'
  ) >= 10 then
    raise exception 'Community post limit reached: maximum 10 designs per 24 hours';
  end if;
  return new;
end;
$$;
revoke all on function public.enforce_community_design_post_limit() from public;

drop trigger if exists community_designs_post_limit on public.community_designs;
create trigger community_designs_post_limit
before insert on public.community_designs
for each row execute function public.enforce_community_design_post_limit();

create or replace function public.enforce_community_report_limit()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if (
    select count(*)
    from public.community_design_reports
    where reporter_id = new.reporter_id
      and created_at > now() - interval '24 hours'
  ) >= 5 then
    raise exception 'Community report limit reached: maximum 5 reports per 24 hours';
  end if;
  return new;
end;
$$;
revoke all on function public.enforce_community_report_limit() from public;

drop trigger if exists community_reports_rate_limit on public.community_design_reports;
create trigger community_reports_rate_limit
before insert on public.community_design_reports
for each row execute function public.enforce_community_report_limit();

-- Keep updated_at current for administrator edits in the dashboard.
create or replace function public.set_updated_at()
returns trigger
language plpgsql
security invoker
set search_path = ''
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists community_designs_set_updated_at on public.community_designs;
create trigger community_designs_set_updated_at
before update on public.community_designs
for each row execute function public.set_updated_at();

