-- Public engagement metrics expose counts, never anonymous-user UUIDs.
create or replace function public.get_community_design_metrics()
returns table (
  design_id uuid,
  like_count bigint,
  remix_count bigint
)
language sql
stable
security definer
set search_path = ''
as $$
  select
    d.id as design_id,
    count(distinct l.user_id) as like_count,
    count(distinct r.id) as remix_count
  from public.community_designs d
  left join public.community_design_likes l on l.design_id = d.id
  left join public.community_designs r on r.parent_id = d.id and r.status = 'published'
  where d.status = 'published'
  group by d.id;
$$;
revoke all on function public.get_community_design_metrics() from public;
grant execute on function public.get_community_design_metrics() to anon, authenticated;

